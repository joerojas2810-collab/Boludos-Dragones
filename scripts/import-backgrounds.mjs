// Importer: painted backgrounds (phase_2_backgrounds) -> public/art/backgrounds/*.webp
// + src/lib/art/backgrounds.generated.ts (scenes, dungeon map, parallax factors). Usage:
//   node scripts/import-backgrounds.mjs "<downloads dir>"
// Combat scenes: 5 layers x (1280x720 desktop, 720x1280 mobile). Screens: composite only.
import sharp from "sharp";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { finder, readJson } from "./lib/art-sources.mjs";

const base = process.argv[2];
if (!base) throw new Error("pass the downloads directory");
const find = finder(base, "backgrounds");
const catalog = readJson(find("scene_catalog.json"));
const manifest = readJson(find("manifest.json"));

const LAYERS = ["sky", "far", "mid", "ground", "foreground"];
const SIZE = { desktop: [1280, 720], mobile: [720, 1280] };
const out = join("public", "art", "backgrounds");
mkdirSync(out, { recursive: true });

const parallax = {};
for (const a of manifest.assets) if (a.kind === "layer") parallax[a.layer] = a.parallax;

let bytes = 0;
const scenes = { combat: [], screen: [] };
for (const s of catalog.scenes) {
  scenes[s.kind].push(s.id);
  const parts = s.kind === "combat" ? LAYERS : ["composite"];
  for (const fmt of ["desktop", "mobile"]) {
    for (const part of parts) {
      const rel = `backgrounds/background_${s.id}_${fmt}_${part}.png`;
      const src = find(rel);
      if (!src) throw new Error(`missing ${rel}`);
      const [w, h] = SIZE[fmt];
      const buf = await sharp(src)
        .resize(w, h)
        .webp({ quality: 80, alphaQuality: 80, effort: 5 })
        .toBuffer();
      bytes += buf.length;
      await sharp(buf).toFile(join(out, `${s.id}_${fmt}_${part}.webp`));
    }
  }
}

writeFileSync(
  join("src", "lib", "art", "backgrounds.generated.ts"),
  `// GENERATED by scripts/import-backgrounds.mjs - do not edit.\n` +
    `export const BG_LAYERS = ${JSON.stringify(LAYERS)} as const;\n` +
    `export const BG_PARALLAX: Record<string, number> = ${JSON.stringify(parallax)};\n` +
    `export const BG_COMBAT_SCENES = ${JSON.stringify(scenes.combat)} as const;\n` +
    `export const BG_SCREEN_SCENES = ${JSON.stringify(scenes.screen)} as const;\n` +
    `// Dungeon rank -> scene ids (normal / boss room).\n` +
    `export const BG_DUNGEON: Record<string, { normal: string; boss: string }> = ${JSON.stringify(
      Object.fromEntries(Object.entries(catalog.dungeons).map(([k, v]) => [k, { normal: v.normal, boss: v.boss }])),
    )};\n`,
);
console.log((bytes / 1e6).toFixed(1), "MB");
